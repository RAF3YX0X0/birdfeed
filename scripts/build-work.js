// MADMarketing's real work (scripts/work-data.js) → the portfolio and the
// homepage's case studies:
//   - fx/portfolio-data.js: the posts, videos and creator videos that the
//     portfolio grid (homepage, /examples/) and the service and industry
//     pages' "work" sections show, filtered by industry, then client,
//   - fx/partials/home-projects.html: the homepage's stacked case-study cards,
//     with charts drawn from the cases' own figures.
// The case studies page itself comes from scripts/build-cases.js.
//
//   node scripts/build-work.js && node scripts/build-cases.js
const fs = require('fs');
const path = require('path');
const { INDUSTRIES, CLIENTS } = require('./work-data');

const ROOT = path.join(__dirname, '..');
const META = JSON.parse(fs.readFileSync(path.join(ROOT, 'work', 'media.json'), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const meta = (src) => {
  if (!META[src]) throw new Error(`missing media ${src} (run scripts/build-work-media.py)`);
  return META[src];
};

// ---- portfolio --------------------------------------------------------------------
const posts = [];
const videos = [];
const ugc = [];
for (const c of CLIENTS) {
  for (const m of c.media) {
    if (m.grid === 0 || !c.ind) continue;
    const info = meta(m.src);
    const base = { ind: c.ind, sub: c.client, c: m.c, f: m.f ? 1 : 0 };
    if (m.kind === 'video') videos.push({ src: m.src, poster: info.poster, ad: m.ad ? 1 : 0, ...base });
    else if (m.kind === 'ugc') ugc.push({ src: m.src, poster: info.poster, ...base });
    else posts.push({ img: m.src, r: +(info.h / info.w).toFixed(2), fmt: m.fmt || '', ...base });
  }
}
const used = INDUSTRIES.filter((ind) => posts.some((p) => p.ind === ind) || videos.some((v) => v.ind === ind));
const subs = Object.fromEntries(used.map((ind) => [ind, CLIENTS.filter((c) => c.ind === ind && posts.some((p) => p.sub === c.client)).map((c) => c.client)]));
const PORTFOLIO = { industries: used, subs, posts, videos, ugc };
fs.writeFileSync(path.join(ROOT, 'fx', 'portfolio-data.js'),
  `// Generated by scripts/build-work.js from scripts/work-data.js (MADMarketing's\n// real client work, media in /work). Do not edit by hand.\nexport const PORTFOLIO = ${JSON.stringify(PORTFOLIO)};\n`);
console.log(`portfolio: ${posts.length} posts, ${videos.length} videos, ${ugc.length} creator videos across ${used.length} industries`);

