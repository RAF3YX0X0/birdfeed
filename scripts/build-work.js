const num = (n) => n.toLocaleString('en-US');

// A results board: one of the case's charts as bars.
function board(ch) {
  const max = Math.max(...ch.rows.map((r) => r[1]));
  return `<div class="pj-board">
            <p class="pj-chart__label">${esc(ch.title)}${ch.note ? ` · ${esc(ch.note)}` : ''}</p>
            <div class="pj-bars">
${ch.rows.slice(0, 4).map(([label, v]) => `              <div class="pj-bars__row" style="--w:${((v / max) * 100).toFixed(1)}%"><span>${esc(label)}</span><i></i><b>${num(v)}</b></div>`).join('\n')}
            </div>
            <p class="pj-board__src">${esc(ch.source)}</p>
          </div>`;
}

// A fan of three pieces of the work itself.
function shots(c, picks) {
  return `<div class="pj-shots">
${picks.map((src) => {
    const m = c.media.find((x) => x.src === src);
    return m.kind === 'video'
      ? `            <video class="pj-shot pj-shot--video" muted loop playsinline preload="none" poster="${esc(meta(src).poster)}" data-pj-play aria-label="${esc(m.c)}"><source src="${esc(src)}" type="video/mp4"></video>`
      : `            <img class="pj-shot" src="${esc(src)}" alt="${esc(m.c)}" loading="lazy" decoding="async">`;
  }).join('\n')}
          </div>`;
}

