// Builds fx/portfolio-data.js for the homepage portfolio store from the
// site's own examples data, keeping only items whose media exists in this
// build (the clone is missing some images and most videos).
//   node scripts/build-portfolio.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const has = (p) => fs.existsSync(path.join(ROOT, p));
const dataFile = fs.readdirSync(path.join(ROOT, '_astro')).find((f) => /^fb-examples-data\..*\.js$/.test(f));
if (!dataFile) throw new Error('fb-examples-data bundle not found');
const { t } = await import(pathToFileURL(path.join(ROOT, '_astro', dataFile)).href);

// Video categories use their own names; map them onto the post industries.
const VIDEO_IND = {
  'Health & Beauty': 'Health & Beauty', Products: 'Products', 'Real Estate': 'Real Estate',
  'Home Services': 'Home Services', Services: 'Professional Services', 'Personal Brands': 'Professional Services',
  B2B: 'Tech & B2B', Solution: 'Tech & B2B', 'Tech/Apps': 'Tech & B2B',
};
const short = (s) => {
  const one = (s || '').replace(/\s+/g, ' ').trim();
  return one.length > 140 ? one.slice(0, 137).replace(/\s+\S*$/, '') + '…' : one;
};

const posts = t.posts
  .filter((p) => has(p.img))
  .map((p) => ({ c: short(p.cap), img: p.img, r: +(p.h / p.w).toFixed(3), ind: p.ind, sub: p.sub, ...(p.feat ? { f: 1 } : {}) }));
const videos = t.videos
  .filter((v) => has(`vx/${v.id}.mp4`) && has(`vx/${v.id}.webp`))
  .map((v) => ({ src: `/vx/${v.id}.mp4`, poster: `/vx/${v.id}.webp`, ind: VIDEO_IND[v.cat] || 'Products', ...(v.ad ? { ad: 1 } : {}) }));
const ugc = fs.readdirSync(path.join(ROOT, 'ugc'))
  .filter((f) => /^ex-.*\.mp4$/.test(f) && has(`ugc/${f.replace('.mp4', '.webp')}`))
  .map((f) => ({ src: `/ugc/${f}`, poster: `/ugc/${f.replace('.mp4', '.webp')}` }));

const out = { industries: t.industries, subs: t.subs, posts, videos, ugc };
const js = `// Generated by scripts/build-portfolio.mjs from the site's examples data —
// only items whose media exists in this build. Do not edit by hand.
export const PORTFOLIO = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(ROOT, 'fx', 'portfolio-data.js'), js);
console.log(`posts ${posts.length}/${t.posts.length}, videos ${videos.length}/${t.videos.length}, ugc ${ugc.length} → fx/portfolio-data.js (${(js.length / 1024).toFixed(0)} KB)`);
