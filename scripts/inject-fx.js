function block(home, shared, hero, nx, ind) {
  const css = [
    'fx.css',
    'chrome.css',
    ...(home || /class="hx /.test(hero) ? ['hero.css'] : []),
    ...(/class="ph/.test(hero) ? ['ph.css'] : []),
    ...(/class="csx/.test(hero) ? ['cases.css'] : []),
    ...(/class="abx"/.test(hero) ? ['about.css'] : []),
    ...(home || shared ? SHARED_CSS : []),
    ...(nx || ind ? ['nx.css', 'ind.css'] : []),
    ...(ind ? ['packages.css'] : []),
    ...(home ? ['nx.css', 'home.css', 'stats.css'] : []),
    // The plans (scripts/offer-render.js): the homepage shows them.
    ...(home ? ['packages.css'] : []),
    ...(ind && !shared ? ['bottom.css'] : []),
  ];
  const font = '<link rel="preload" as="font" type="font/woff2" href="/fonts/satoshi-variable.woff2" crossorigin>';
  if (manifest) {
    return [
      START,
      `<link rel="stylesheet" href="${cssBundle(css)}">`,
      font,
      // Homepage: the hero phone's poster is the biggest thing on a phone's first screen.
      `<script>${manifest.boot}</script>`,
      `<script src="${manifest.vendor}" defer></script>`,
      ...manifest.eager.map((c) => `<link rel="modulepreload" href="${c}">`),
      `<script type="module" src="${manifest.js}"></script>`,
      SPECULATION,
      CONSENT,
      GA4,
      END,
    ].join('\n');
  }
  return [
    START,
    ...css.map((f) => `<link rel="stylesheet" href="/fx/${f}">`),
    font,
    '<script src="/fx/boot.js"></script>',
    '<script src="/fx/vendor/gsap.min.js" defer></script>',
    '<script src="/fx/vendor/ScrollTrigger.min.js" defer></script>',
    '<script src="/fx/vendor/lenis.min.js" defer></script>',
    '<script type="module" src="/fx/fx.js"></script>',
    CONSENT,
    GA4,
    END,
  ].join('\n');
}

function pages(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.') || entry.name === 'fx') continue;
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) pages(p, out);
    else if (entry.name.endsWith('.html')) out.push(p);
  }
  return out;
}

let changed = 0;
// Standalone pages with their own markup and styles (no React, no FX layer).
const STANDALONE = ['login'];
for (const file of pages(ROOT)) {
  if (STANDALONE.includes(path.relative(ROOT, path.dirname(file)).split(path.sep).join('/'))) continue;
  const src = fs.readFileSync(file, 'utf8');
  let html = src;
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a !== -1 && b !== -1) html = html.slice(0, a).replace(/\n$/, '') + html.slice(b + END.length).replace(/^\n/, '');
  const home = file === HOME;
  for (const blk of BLOCKS) {
    const s = html.indexOf(blk.start);
    const e = html.indexOf(blk.end);
    if (s !== -1 && e !== -1) html = html.slice(0, s) + html.slice(e + blk.end.length);
  }
  if (!remove) {
    const i = html.indexOf('</head>');
    if (i === -1) { console.warn('no </head>:', path.relative(ROOT, file)); continue; }
    const shared = home ? '' : sharedFor(file, html);
    let hero = home ? '' : heroFor(file);
    // The examples page: our clients' work (the homepage's portfolio grid) in
    // place of the cloned gallery, which showed another agency's clients.
    // The cloned gallery was only hidden with CSS, so its island still
    // hydrated and then fetched all 407 of that agency's images — 51MB and
    // 724 requests on the first screen, none of it ever seen. isExamples also
    // switches the island off below; the only part of it still on show was the
    // closing call, so that goes in here instead.
    const isExamples = path.relative(ROOT, path.dirname(file)) === 'examples';
    if (hero && isExamples) {
      hero += '\n<style>astro-island[component-export="ExamplesIndex"] { display: none !important; }</style>\n'
        + partial('home-portfolio.html') + '\n' + sharedSection('ct');
    }
    const nx = home ? '' : sectionsFor(file);
    const ind = home ? null : industryFor(file);
    html = html.slice(0, i) + '\n' + block(home, !!shared, hero, !!nx, !!ind) + '\n' + html.slice(i);
    // Ad landing pages (<html data-fx-landing>) bring their own slim nav and
    // footer, so visitors stay on the offer.
    // The cloned React sections are hidden on every page — our own sections
    // replaced them — so there is nothing for React to render. Leaving the
    // islands to hydrate anyway cost 99 requests and 21MB across the site, in
    // chunks, that agency's images and its review posters. Renaming the two
    // attributes Astro reads leaves the markup exactly where it is (so nothing
    // can mismatch) while stopping the component ever being fetched or run.
    //
    // REACT_PAGES are the exceptions: on these the 3D explainer finds its place
    // by matching text that the cloned sections render, so switching them off
    // would drop the explainer. Verified by snapshotting every page with the
    // islands on and off and comparing what each one shows.
    const slug = path.relative(ROOT, path.dirname(file)).split(path.sep)[0];
    const keepReact = REACT_PAGES.has(slug);
    html = html.replace(/<astro-island\b[^>]*>/g, (tag) => {
      const url = (tag.match(/component-url="([^"]+)"/) || [])[1];
      // An island whose chunk isn't in _astro can never hydrate in any case:
      // the request simply 404s. Those go quiet even on the React pages.
      const dead = !url || !fs.existsSync(path.join(ROOT, url.replace(/^\//, '')));
      if (keepReact && !dead) return tag;
      return tag.replace(/\sclient="/, ' data-fx-noclient="').replace(/\scomponent-url="/, ' data-fx-nourl="');
    });
    const landing = /<html[^>]*\sdata-fx-landing/.test(html);
    for (const blk of BLOCKS) {
      if (landing && (blk.name === 'nav' || blk.name === 'footer')) continue;
      if (blk.home && !home) continue;
      if (blk.inner && (home || !shared)) continue;
      if (blk.name === 'pagehero' && !hero) continue;
      if (blk.name === 'sections' && !nx) continue;
      if (blk.name.startsWith('industry') && !ind) continue;
      let k = -1;
      if (blk.at === 'main-start') {
        const m = html.indexOf('<main');
        k = m === -1 ? -1 : html.indexOf('>', m) + 1;
      } else if (blk.at === 'first-island') {
        k = html.indexOf('<astro-island', html.indexOf('<main'));
      } else if (blk.at === 'main-end') {
        k = html.lastIndexOf('</main>');
      } else {
        const at = html.indexOf(`component-export="${blk.island}"`);
        k = at === -1 ? -1 : html.lastIndexOf('<astro-island', at);
      }
      if (k <= 0) { console.warn(`no place for ${blk.name}:`, path.relative(ROOT, file)); continue; }
      const extra = blk.name === 'nav' && !home && !hero ? NAV_SPACE : blk.name === 'shared' ? shared : blk.name === 'pagehero' ? hero : blk.name === 'sections' ? nx : blk.name === 'industry-top' ? ind.top : blk.name === 'industry-bottom' ? ind.bottom : '';
      let body = blk.files.map(partial).join('\n');
      if (blk.insert) {
        const at = body.indexOf(blk.insert.before);
        if (at === -1) console.warn(`no "${blk.insert.before}" in ${blk.name}`);
        else body = body.slice(0, at) + partial(blk.insert.file) + '\n' + body.slice(at);
      }
      if (blk.edit) body = blk.edit(body);
      html = html.slice(0, k) + blk.start + body + extra + blk.end + html.slice(k);
    }
  }
  if (html !== src) {
    fs.writeFileSync(file, html);
    changed++;
  }
}
