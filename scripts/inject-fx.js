const sectionsOf = (file) => {
  const out = {};
  partial(file).split(/\n(?=<section class=")/).forEach((s) => {
    const m = s.match(/^<section class="([a-z]+)"/);
    if (m) out[m[1]] = s.trim();
  });
  return out;
};
// One shared section's markup by class, for pages that need it placed
// statically rather than swapped in over a cloned one.
function sharedSection(cls) {
  const all = Object.assign({}, ...['home-trust.html', 'home-hiw.html', 'home-portfolio.html', 'home-projects.html', 'home-bottom.html'].map(sectionsOf));
  return all[cls] || '';
}

function sharedFor(file, html) {
  const slug = path.relative(ROOT, path.dirname(file)).split(path.sep)[0];
  if (!slug || LEGAL.includes(slug)) return '';
  const body = html.slice(html.indexOf('<astro-island'));
  const all = Object.assign({}, ...['home-trust.html', 'home-hiw.html', 'home-portfolio.html', 'home-projects.html', 'home-bottom.html'].map(sectionsOf));
  // Service and category pages keep only the closing call to action (worded
  // for the page); the other shared sections are general, not about the
  // service. Industry pages build their own (none of these).
  const type = (html.match(/component-export="(ServicePage|CategoryPage|IndustryPage)"/) || [])[1];
  if (type === 'IndustryPage' || slug === 'about') return ''; // (about: scripts/build-about.js)
  const want = SHARED.filter(({ cls, re }) => re.test(body) && !(KEEP[slug] || []).includes(cls) && all[cls] && (!type || cls === 'ct'));
  if (!want.length) return '';
  return `<template id="fx-shared">${want.map(({ cls }) => all[cls]).join('\n')}</template>`;
}

// Three.js is deliberately not preloaded: fx.js imports it on demand while the
// intro curtain plays, which keeps it off the critical path to DOMContentLoaded.
// The generated hero for an inner page ('' if none).
function heroFor(file) {
  const slug = path.relative(ROOT, path.dirname(file)).split(path.sep).join('__');
  const f = path.join(ROOT, 'fx', 'partials', 'heroes', slug + '.html');
  return slug && fs.existsSync(f) ? fs.readFileSync(f, 'utf8').trim() : '';
}

// Production build (scripts/build-fx.js): bundled, minified, content-hashed
// files in fx/dist/. Without it, pages load the sources directly.
const DIST = path.join(ROOT, 'fx', 'dist');
const MANIFEST = path.join(DIST, 'manifest.json');
const manifest = !remove && fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : null;
let esbuild = null;
try { esbuild = require('esbuild'); } catch (e) { /* stylesheets are joined but not minified */ }
const cssBundles = new Map();
// A page's stylesheets as one minified file (one request instead of up to ten).
function cssBundle(list) {
  const key = list.join('|');
  if (cssBundles.has(key)) return cssBundles.get(key);
  const src = list.map((f) => fs.readFileSync(path.join(ROOT, 'fx', f), 'utf8')).join('\n');
  const out = esbuild ? esbuild.transformSync(src, { loader: 'css', minify: true }).code : src;
  const name = `css-${require('crypto').createHash('sha256').update(out).digest('hex').slice(0, 10)}.css`;
  if (!fs.existsSync(path.join(DIST, name))) fs.writeFileSync(path.join(DIST, name), out);
  cssBundles.set(key, `/fx/dist/${name}`);
  return cssBundles.get(key);
}

// An inner page's rebuilt sections ('' if none): a <style> hiding the
// originals and a <template> that fx/sections.js swaps in.
function sectionsFor(file) {
  const slug = path.relative(ROOT, path.dirname(file)).split(path.sep).join('__');
  const f = path.join(ROOT, 'fx', 'partials', 'sections', slug + '.html');
  return slug && fs.existsSync(f) ? fs.readFileSync(f, 'utf8').trim() : '';
}

